    public function fetchResults()
    {

        foreach ($this->roles as $roll) {

            $response = Http::asForm()->post(
                'https://result.dinajpurboard.gov.bd/hsc_result2025/search/search_student.php',
                [
                    'roll_no' => $roll,
                    'regi_no' => '',
                    'submit' => ''
                ]
            );

            $html = $response->body();

            libxml_use_internal_errors(true);
            $dom = new \DOMDocument();
            $dom->loadHTML($html);
            $xpath = new \DOMXPath($dom);

            $tds = $xpath->query("//table//tr/td");

            if ($tds->length < 10) {
                continue;
            }

            $roll_no = trim($tds->item(1)->nodeValue);
            $student_name = trim($tds->item(5)->nodeValue);
            $father_name = trim($tds->item(7)->nodeValue);
            $mother_name = trim($tds->item(9)->nodeValue);

            $result_text = trim($tds->item(17)->nodeValue);
            preg_match('/GPA=([0-9.]+)/', $result_text, $matches);
            $gpa = $matches[1] ?? null;

            DB::table('student_info')->updateOrInsert(
                ['roll_no' => $roll_no],
                [
                    'student_name' => $student_name,
                    'father_name' => $father_name,
                    'mother_name' => $mother_name,
                    'gpa' => $gpa,
                    'created_at' => now(),
                    'updated_at' => now()
                ]
            );
        }

        return response()->json([
            'message' => 'Data fetched and stored successfully'
        ]);
    }
